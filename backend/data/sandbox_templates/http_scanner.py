# CLI
# ---------------------------------------------------------------------------

def main() -> int:
    parser = argparse.ArgumentParser(description="Lucy AI Agent — HTTP Endpoint Scanner")
    parser.add_argument("--target", required=True, help="Base URL to scan (e.g., http://localhost:8080)")
    parser.add_argument("--wordlist", help="Path to wordlist file (one path per line)")
    parser.add_argument("--workers", type=int, default=10, help="Concurrent workers (default: 10)")
    parser.add_argument("--timeout", type=int, default=10, help="Request timeout in seconds (default: 10)")
    parser.add_argument("--output", default="/workspace/logs", help="Output directory for JSON logs")
    args = parser.parse_args()

    # Setup logging
    log_file = setup_logging(args.output)
    logger = logging.getLogger("http_scanner")

    print(f"[*] Lucy HTTP Scanner starting...")
    print(f"[*] Target: {args.target}")
    print(f"[*] Log file: {log_file}")

    # Resolve host
    host_info = resolve_host(args.target)
    log_result(logger, host_info)
    print(f"[+] Host: {host_info.get('hostname')} -> {host_info.get('ip')}:{host_info.get('port')}")

    # Load wordlist
    if args.wordlist and Path(args.wordlist).exists():
        with open(args.wordlist, "r") as f:
            wordlist = [line.strip() for line in f if line.strip() and not line.startswith("#")]
    else:
        wordlist = default_wordlist()
        print(f"[*] Using default wordlist ({len(wordlist)} paths)")

    # Scan
    print(f"[*] Scanning {len(wordlist)} endpoints with {args.workers} workers...")
    findings = discover_endpoints(args.target, wordlist, args.workers)

    # Log and summarize
    success_count = sum(1 for f in findings if f["status"] == "success")
    error_count = sum(1 for f in findings if f["status"] == "error")
    warning_count = sum(1 for f in findings if f["status"] == "warning")

    for finding in findings:
        log_result(logger, finding)
        if finding["status_code"] and finding["status_code"] < 400:
            print(f"[+] {finding['path']:30} -> {finding['status_code']} ({finding['response_time_ms']}ms)")
        elif finding["status_code"]:
            print(f"[-] {finding['path']:30} -> {finding['status_code']} ({finding['error']})")
        else:
            print(f"[!] {finding['path']:30} -> ERROR ({finding['error']})")

    summary = {
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "tool": "http_scanner",
        "target": args.target,
        "status": "success",
        "total_scanned": len(wordlist),
        "success": success_count,
        "warnings": warning_count,
        "errors": error_count,
        "log_file": str(log_file),
    }
    log_result(logger, summary)

    print(f"\n[*] Scan complete.")
    print(f"    Success: {success_count} | Warnings: {warning_count} | Errors: {error_count}")
    print(f"    Log: {log_file}")

    return 0 if error_count == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
